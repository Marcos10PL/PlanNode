import {
  PROJECT_COLORS,
  PROJECT_ICONS,
  VALIDATION_MAX,
  VALIDATION_MAX_HTML,
  VALIDATION_MIN,
} from "@/const";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT = path.join(__dirname, "../supabase/schemas/limits.sql");

type Length = { table: string; column: string; min?: number; max: number };

const required = (table: string, column: string, max: number): Length => ({
  table,
  column,
  min: VALIDATION_MIN.NAME,
  max,
});

const optional = (table: string, column: string, max: number): Length => ({
  table,
  column,
  max,
});

const LENGTHS: Length[] = [
  required("profiles", "full_name", VALIDATION_MAX.FULL_NAME),
  required("workspaces", "name", VALIDATION_MAX.WORKSPACE_NAME),
  optional("workspaces", "description", VALIDATION_MAX.WORKSPACE_DESCRIPTION),
  required("projects", "name", VALIDATION_MAX.PROJECT_NAME),
  optional("projects", "description", VALIDATION_MAX.PROJECT_DESCRIPTION),
  required("task_lists", "name", VALIDATION_MAX.TASK_LIST_NAME),
  required("tasks", "title", VALIDATION_MAX.TASK_TITLE),
  optional("tasks", "description", VALIDATION_MAX_HTML.TASK_DESCRIPTION),
  optional("task_comments", "content", VALIDATION_MAX_HTML.TASK_COMMENT),
  optional("workspace_invitations", "email", VALIDATION_MAX.EMAIL),
];

const ENUMS = [
  { table: "projects", column: "color", values: Object.values(PROJECT_COLORS) },
  { table: "projects", column: "icon", values: Object.values(PROJECT_ICONS) },
];

const lengthCheck = ({ column, min, max }: Length) =>
  min === undefined
    ? `char_length(${column}) <= ${max}`
    : `char_length(btrim(${column})) BETWEEN ${min} AND ${max}`;

const statements = [
  ...LENGTHS.map(
    l =>
      `ALTER TABLE public.${l.table}\n  ADD CONSTRAINT ${l.table}_${l.column}_length CHECK (${lengthCheck(l)});`,
  ),
  ...ENUMS.map(
    e =>
      `ALTER TABLE public.${e.table}\n  ADD CONSTRAINT ${e.table}_${e.column}_allowed CHECK (${e.column} IN (${e.values.map(v => `'${v}'`).join(", ")}));`,
  ),
];

const content = `-- GENERATED by scripts/generate-limits.ts from const/index.ts

${statements.join("\n\n")}
`;

if (process.argv.includes("--check")) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, "utf8") : "";
  if (current.replace(/\r\n/g, "\n") !== content) {
    console.error(
      "supabase/schemas/limits.sql is out of date. Run `pnpm generate-limits`.",
    );
    process.exit(1);
  }
  console.log("supabase/schemas/limits.sql is up to date.");
} else {
  writeFileSync(OUTPUT, content);
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)}`);
}
